package com.ecotrack.backend.service;

import com.ecotrack.backend.dto.AnomalyCheckResponse;
import com.ecotrack.backend.dto.BudgetStatusResponse;
import com.ecotrack.backend.exception.ApiException;
import com.ecotrack.backend.model.Recommendation;
import com.ecotrack.backend.model.UserAccount;
import com.ecotrack.backend.model.UserRole;
import com.ecotrack.backend.repository.RecommendationRepository;
import org.springframework.http.HttpStatus;
import org.springframework.stereotype.Service;

import java.time.Instant;
import java.time.YearMonth;
import java.util.Comparator;
import java.util.List;
import java.util.UUID;

/**
 * Persists and tracks completion of recommendations generated by three sources:
 * <ul>
 *   <li>APPLIANCE — from ApplianceService.buildRecommendationTips, key "appliance:" + applianceId + ":" + tipKind</li>
 *   <li>BUDGET — from BudgetService.getTriggeredAlertHits, key "budget:" + utilityKey + ":threshold-" + threshold</li>
 *   <li>ANOMALY — from AnomalyDetectionService.checkUnusualConsumption, key "anomaly:" + utilityType + ":" + billingMonth</li>
 * </ul>
 * Each key is stable across repeated generation so the same underlying tip is recognized (and its
 * completed/completedAt state preserved) even as its wording changes slightly between calls.
 */
@Service
public class RecommendationService {

    private final RecommendationRepository recommendationRepository;
    private final AuthService authService;
    private final ApplianceService applianceService;
    private final BudgetService budgetService;
    private final AnomalyDetectionService anomalyDetectionService;

    public RecommendationService(
            RecommendationRepository recommendationRepository,
            AuthService authService,
            ApplianceService applianceService,
            BudgetService budgetService,
            AnomalyDetectionService anomalyDetectionService
    ) {
        this.recommendationRepository = recommendationRepository;
        this.authService = authService;
        this.applianceService = applianceService;
        this.budgetService = budgetService;
        this.anomalyDetectionService = anomalyDetectionService;
    }

    public List<Recommendation> getActiveRecommendations(String token) {
        UserAccount user = authService.requireUser(token);
        String userId = user.getId();

        // (a) Appliance tips.
        for (ApplianceService.Tip tip : applianceService.buildRecommendationTips(token)) {
            upsertRecommendation(userId, tip.key(), "APPLIANCE", tip.text());
        }

        // (b) Budget threshold alerts.
        for (BudgetService.ThresholdHit hit : budgetService.getTriggeredAlertHits(token)) {
            String key = "budget:" + hit.utilityKey() + ":threshold-" + hit.threshold();
            upsertRecommendation(userId, key, "BUDGET", hit.message());
        }

        // (c) Anomaly detections, both utilities.
        String currentMonth = YearMonth.now().toString();
        for (String utilityType : List.of("ELECTRICITY", "WATER")) {
            AnomalyCheckResponse anomaly = anomalyDetectionService.checkUnusualConsumption(token, utilityType);
            if (anomaly.hasEnoughData() && anomaly.isUnusual()) {
                String key = "anomaly:" + utilityType + ":" + currentMonth;
                upsertRecommendation(userId, key, "ANOMALY", buildAnomalyText(anomaly));
            }
        }

        return recommendationRepository.findByUserId(userId).stream()
                .sorted(Comparator.comparing(Recommendation::isCompleted)
                        .thenComparing(Comparator.comparing(Recommendation::getCreatedAt,
                                Comparator.nullsLast(Comparator.reverseOrder()))))
                .toList();
    }

    private String buildAnomalyText(AnomalyCheckResponse anomaly) {
        StringBuilder sb = new StringBuilder();
        sb.append(anomaly.message());
        if (!anomaly.possibleCauses().isEmpty()) {
            sb.append(" Possible causes: ").append(String.join("; ", anomaly.possibleCauses())).append(".");
        }
        if (!anomaly.recommendedActions().isEmpty()) {
            sb.append(" Recommended actions: ").append(String.join("; ", anomaly.recommendedActions())).append(".");
        }
        return sb.toString();
    }

    /**
     * If a Recommendation with this userId+key already exists, update its text (wording may
     * change slightly between generations) but PRESERVE its completed/completedAt state.
     * Otherwise insert a new, not-completed row.
     */
    private void upsertRecommendation(String userId, String key, String category, String text) {
        Recommendation existing = recommendationRepository.findByUserIdAndRecommendationKey(userId, key).orElse(null);
        if (existing != null) {
            existing.setText(text);
            existing.setCategory(category);
            recommendationRepository.save(existing);
            return;
        }

        Recommendation recommendation = new Recommendation();
        recommendation.setId(UUID.randomUUID().toString());
        recommendation.setUserId(userId);
        recommendation.setRecommendationKey(key);
        recommendation.setCategory(category);
        recommendation.setText(text);
        recommendation.setCompleted(false);
        recommendation.setCreatedAt(Instant.now());
        recommendationRepository.save(recommendation);
    }

    public Recommendation markCompleted(String token, String id, boolean completed) {
        UserAccount user = authService.requireUser(token);
        Recommendation recommendation = recommendationRepository.findById(id)
                .orElseThrow(() -> new ApiException(HttpStatus.NOT_FOUND, "Recommendation not found."));

        boolean owns = recommendation.getUserId() != null && recommendation.getUserId().equals(user.getId());
        boolean isAdmin = user.getRole() == UserRole.ADMIN;
        if (!owns && !isAdmin) {
            throw new ApiException(HttpStatus.FORBIDDEN, "You do not have access to this recommendation.");
        }

        recommendation.setCompleted(completed);
        recommendation.setCompletedAt(completed ? Instant.now() : null);
        return recommendationRepository.save(recommendation);
    }
}
